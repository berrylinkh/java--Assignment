	
/* PSUEDOCODE FOR REVERSE TO FORWARD
1 START
2. CREATE A CLASS AND A MAIN METHOD
3. INITIAL FOR LOOP FOR POSITIVE AND NEGATIVE COUNTER 
4. CLOSE LOOP
5. DISPLAY THE RESULT AT THE PROGRAM.
6. END */

	public class ReverseToForward{
	public static void main (String [] args) {


	for(int number = 7; number >= 1; number --) {
	System.out.print( number + " " );

		}

	for(int number = 2; number <= 7; number ++) {
	System.out.print( number + " " );

		}

	}
}